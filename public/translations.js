// Fonction pour obtenir la traduction
// Les clés sont stockées à plat ('acc.nav.accueil'), pas en objets imbriqués.
function t(key, lang = null) {
  const langue = lang || (localStorage.getItem('langue') || 'fr');
  const table = translations[langue] || translations.fr;

  // 1) clé plate dans la langue demandée
  if (table && Object.prototype.hasOwnProperty.call(table, key)) return table[key];

  // 2) repli sur le français
  if (translations.fr && Object.prototype.hasOwnProperty.call(translations.fr, key)) return translations.fr[key];

  // 3) compatibilité : structure imbriquée éventuelle
  let text = table;
  for (const part of key.split('.')) {
    if (text && typeof text === 'object' && part in text) text = text[part];
    else return key;
  }
  return typeof text === 'string' ? text : key;
}

// Fonction pour changer de langue
function changerLangue(langue) {
  localStorage.setItem('langue', langue);
  document.documentElement.lang = langue;
  document.body.dataset.langue = langue;
  // Appliquer traductions sans recharger
  appliquerTraductions(langue);
  // Mettre à jour le bouton langue
  const btn = document.getElementById('btnLangue');
  if (btn) {
    btn.textContent = langue === 'fr' ? '🌐 HT' : '🌐 FR';
  }
}


// Fonction pour appliquer les traductions automatiquement
function appliquerTraductions(lang = null) {
  const langue = lang || getLangue();
  /* Une cle absente des deux tables fait renvoyer la cle elle-meme par
     `t`. L'ecrire dans la page remplacait un texte lisible par
     « tu.e.t1 » : le visiteur se retrouvait devant du charabia. Le texte
     deja present dans le HTML est alors conserve. */
  const traduit = (key) => { const v = t(key, langue); return v === key ? null : v; };
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const v = traduit(el.getAttribute('data-i18n'));
    if (v !== null) el.textContent = v;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const v = traduit(el.getAttribute('data-i18n-placeholder'));
    if (v !== null) el.placeholder = v;
  });
}

// Obtenir la langue courante
function getLangue() {
  return localStorage.getItem('langue') || 'fr';
}

// Initialiser la langue au chargement
window.addEventListener('DOMContentLoaded', () => {
  const langue = getLangue();
  document.documentElement.lang = langue;
  document.body.dataset.langue = langue;
  appliquerTraductions(langue);
  const btn = document.getElementById('btnLangue');
  if (btn) btn.textContent = langue === 'fr' ? '🌐 HT' : '🌐 FR';
});
